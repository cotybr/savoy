-- Tabela de solicitações de RH/banco de horas
create table if not exists public.solicitacoes (
  id            bigint generated by default as identity primary key,
  matricula     text not null check (matricula ~ '^[A-Za-z0-9]{3,20}$'),
  nome          text not null check (char_length(nome) between 3 and 120),
  tipo          text not null check (tipo in ('consulta_horas','ajuste_ponto','duvida_rh','alocacao_linha')),
  mensagem      text not null check (char_length(mensagem) between 1 and 2000),
  status        text not null default 'pendente'
                 check (status in ('pendente','em_analise','concluido')),
  created_at    timestamptz not null default now()
);

alter table public.solicitacoes enable row level security;

-- Nenhum acesso anônimo por padrão
revoke all on public.solicitacoes from anon, authenticated;

-- Permitir apenas INSERT (com validação) para anon
grant insert on public.solicitacoes to anon;
grant usage, select on sequence public.solicitacoes_id_seq to anon;

create policy "anon_pode_inserir_solicitacao"
  on public.solicitacoes
  for insert
  to anon
  with check (
    char_length(mensagem) between 1 and 2000
    and char_length(nome) between 3 and 120
    and matricula ~ '^[A-Za-z0-9]{3,20}$'
    and tipo in ('consulta_horas','ajuste_ponto','duvida_rh','alocacao_linha')
  );

-- (Opcional) leitura controlada apenas do próprio registro via RPC
-- Não habilitamos SELECT direto para anon: o colaborador não deve listar tudo.

-- Se quiser permitir leitura limitada (ex.: por matrícula), crie uma RPC SECURITY DEFINER:
create or replace function public.minhas_solicitacoes(p_matricula text)
returns setof public.solicitacoes
language sql
security definer
set search_path = public
as $$
  select * from public.solicitacoes
  where matricula = p_matricula
  order by created_at desc
  limit 20;
$$;

revoke all on function public.minhas_solicitacoes(text) from public;
grant execute on function public.minhas_solicitacoes(text) to anon;